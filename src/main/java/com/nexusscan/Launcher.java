package com.nexusscan;

import javafx.application.Application;

/**
 * Entry point launcher class for the NexusScan application.
 * This class is used to bootstrap the JavaFX application environment.
 */
public class Launcher {
    /**
     * Main method that launches the NexusScan application.
     *
     * @param args Command-line arguments passed to the application.
     */
    public static void main(String[] args) {
        Application.launch(NexusScanApplication.class, args);
    }
}
